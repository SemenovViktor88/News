package com.semenov.news.core.db

import android.content.ContentValues
import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.semenov.news.core.db.entity.ArticleEntity
import com.semenov.news.core.db.entity.CachedPageEntity
import java.util.UUID
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.withContext
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class NewsDatabaseUpgradeTest {
    private val context = InstrumentationRegistry.getInstrumentation().targetContext
    private val databaseName = "room_upgrade_${UUID.randomUUID()}.db"
    private var database: NewsDatabase? = null

    @After
    fun tearDown() {
        database?.close()
        context.deleteDatabase(databaseName)
    }

    @Test
    fun cacheFromRoom272SurvivesUpgradeAndNewWritesSurviveReopening() = runBlocking {
        seedRoom272Database()
        val original = openDatabase().articleDao()

        assertEquals(listOf(legacyArticle), original.articlesForPage(CONTEXT, 1))
        assertEquals(CachedPageEntity(CONTEXT, 1, 20, 100L), original.cachedPage(CONTEXT, 1))
        // An empty cached page is still a downloaded page, not a cache miss.
        assertEquals(CachedPageEntity(CONTEXT, 2, 20, 100L), original.cachedPage(CONTEXT, 2))
        assertTrue(original.articlesForPage(CONTEXT, 2).isEmpty())

        val secondArticle = legacyArticle.copy(url = "https://example.com/new", page = 2, cachedAt = 200L)
        original.insertArticlesIgnoringDuplicates(listOf(secondArticle))
        original.upsertCachedPage(CachedPageEntity(CONTEXT, 2, 21, 200L))
        database!!.close()
        val reopened = openDatabase().articleDao()

        assertEquals(listOf(legacyArticle), reopened.articlesForPage(CONTEXT, 1))
        assertEquals(listOf(secondArticle), reopened.articlesForPage(CONTEXT, 2))
        assertEquals(CachedPageEntity(CONTEXT, 2, 21, 200L), reopened.cachedPage(CONTEXT, 2))
    }

    @Test
    fun clearingUpgradedDatabaseRemovesAllCacheAcrossReopeningAndAllowsNewSessionWrites() = runBlocking {
        seedRoom272Database()
        val upgraded = openDatabase()

        withContext(Dispatchers.IO) { upgraded.clearAllTables() }
        upgraded.close()
        val reopened = openDatabase().articleDao()

        assertTrue(reopened.articlesForPage(CONTEXT, 1).isEmpty())
        assertNull(reopened.cachedPage(CONTEXT, 1))
        assertNull(reopened.cachedPage(CONTEXT, 2))

        reopened.insertArticlesIgnoringDuplicates(listOf(legacyArticle))
        reopened.upsertCachedPage(CachedPageEntity(CONTEXT, 1, 1, 300L))
        assertEquals(listOf(legacyArticle), reopened.articlesForPage(CONTEXT, 1))
        assertEquals(CachedPageEntity(CONTEXT, 1, 1, 300L), reopened.cachedPage(CONTEXT, 1))
    }

    private fun openDatabase(): NewsDatabase = Room.databaseBuilder(
        context,
        NewsDatabase::class.java,
        databaseName,
    ).fallbackToDestructiveMigration(dropAllTables = true)
        .build()
        .also { database = it }

    private fun seedRoom272Database() {
        val file = context.getDatabasePath(databaseName)
        file.parentFile!!.mkdirs()
        SQLiteDatabase.openOrCreateDatabase(file, null).use { legacy ->
            // Frozen schema and Room identity from the v2 export generated by Room 2.7.2.
            // Do not derive these from current generated code: this must model an existing install.
            legacy.execSQL(
                """
                CREATE TABLE articles (
                    contextKey TEXT NOT NULL, url TEXT NOT NULL, title TEXT, description TEXT,
                    imageUrl TEXT, publishedAt TEXT, sourceName TEXT, author TEXT, content TEXT,
                    page INTEGER NOT NULL, position INTEGER NOT NULL, cachedAt INTEGER NOT NULL,
                    PRIMARY KEY(contextKey, url)
                )
                """.trimIndent(),
            )
            legacy.execSQL(
                """
                CREATE TABLE cached_pages (
                    contextKey TEXT NOT NULL, page INTEGER NOT NULL, totalResults INTEGER NOT NULL,
                    cachedAt INTEGER NOT NULL, PRIMARY KEY(contextKey, page)
                )
                """.trimIndent(),
            )
            legacy.execSQL("CREATE TABLE room_master_table (id INTEGER PRIMARY KEY, identity_hash TEXT)")
            legacy.execSQL(
                "INSERT INTO room_master_table (id, identity_hash) VALUES (42, '59cdde28428e8650c9d677d78129cdf0')",
            )
            legacy.version = 2
            legacy.insertOrThrow(
                "articles",
                null,
                ContentValues().apply {
                    put("contextKey", CONTEXT)
                    put("url", legacyArticle.url)
                    put("title", legacyArticle.title)
                    put("description", legacyArticle.description)
                    put("publishedAt", legacyArticle.publishedAt)
                    put("sourceName", legacyArticle.sourceName)
                    put("page", 1)
                    put("position", 0)
                    put("cachedAt", 100L)
                },
            )
            legacy.execSQL("INSERT INTO cached_pages VALUES (?, 1, 20, 100)", arrayOf(CONTEXT))
            legacy.execSQL("INSERT INTO cached_pages VALUES (?, 2, 20, 100)", arrayOf(CONTEXT))
        }
    }

    private companion object {
        const val CONTEXT = "headlines:ua"
        val legacyArticle = ArticleEntity(
            contextKey = CONTEXT,
            url = "https://example.com/saved",
            title = "Збережені новини",
            description = "Кеш до оновлення Room",
            imageUrl = null,
            publishedAt = "2026-10-26T10:00:00Z",
            sourceName = "News",
            author = null,
            content = null,
            page = 1,
            position = 0,
            cachedAt = 100L,
        )
    }
}
